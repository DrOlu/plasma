"""Strict Pydantic v2 contract for a normalized Plasma EDR event.

Generated by neuralOS from samples/plasma_events.jsonl, then hand-tuned for
fleet use:

* true enums stay enums (kind, severity, source, action);
* identity fields (host, user, process, parent, paths, addresses) are
  pattern-constrained strings, NOT closed Literals — a frozen instance must
  accept hosts and users it has never seen;
* nullable fields stay Optional exactly where the source has nulls.

Every record passes through this model at the bridge boundary. A parse
failure is counted into _VALIDATION, never silently accepted.
"""
from __future__ import annotations

from datetime import datetime
from typing import Any, Literal, Optional

from pydantic import BaseModel, ConfigDict, Field, field_validator

DT_FORMATS = [
    "%Y-%m-%dT%H:%M:%S.%f%z", "%Y-%m-%dT%H:%M:%S%z",
    "%Y-%m-%dT%H:%M:%S.%f", "%Y-%m-%dT%H:%M:%S",
    "%Y-%m-%d %H:%M:%S", "%Y-%m-%d",
]


def _parse_dt(value: Any) -> Any:
    if isinstance(value, datetime) or not isinstance(value, str):
        return value
    for fmt in DT_FORMATS:
        try:
            return datetime.strptime(value.strip(), fmt)
        except ValueError:
            continue
    raise ValueError(f"unrecognized datetime spelling: {value!r}")


class PlasmaEvent(BaseModel):
    """One normalized endpoint event (Sentinel alert, Sysmon event or trace)."""

    model_config = ConfigDict(
        extra="forbid", populate_by_name=True, str_strip_whitespace=True
    )

    ts: datetime
    host: str = Field(pattern=r"^[A-Za-z0-9][A-Za-z0-9._-]{0,62}$")
    source: Literal["sentinel", "sysmon", "sealighter", "plasma"]
    kind: Literal[
        "alert", "auth", "dns", "file", "image_load",
        "network", "process", "registry",
    ]
    event_id: int = Field(ge=1, le=99999)
    severity: Literal["info", "low", "medium", "high", "critical"]
    user: Optional[str] = Field(default=None, max_length=128)
    process: Optional[str] = Field(default=None, max_length=260)
    pid: Optional[int] = Field(default=None, ge=0, le=2_147_483_647)
    ppid: Optional[int] = Field(default=None, ge=0, le=2_147_483_647)
    parent: Optional[str] = Field(default=None, max_length=260)
    image: Optional[str] = Field(default=None, max_length=4096)
    cmdline: Optional[str] = Field(default=None, max_length=8192)
    dest_ip: Optional[str] = Field(
        default=None, pattern=r"^[0-9A-Fa-f:.]{2,45}$"
    )
    dest_port: Optional[int] = Field(default=None, ge=0, le=65535)
    dns_query: Optional[str] = Field(default=None, max_length=253)
    file_path: Optional[str] = Field(default=None, max_length=4096)
    file_hash: Optional[str] = Field(default=None, pattern=r"^[A-Fa-f0-9]{64}$")
    registry_path: Optional[str] = Field(default=None, max_length=4096)
    technique: Optional[str] = Field(
        default=None, pattern=r"^T\d{4}(\.\d{3})?$"
    )
    alert_id: Optional[str] = Field(default=None, max_length=64)
    score: Optional[float] = Field(default=None, ge=0.0, le=1.0)
    action: Optional[Literal["allowed", "blocked", "quarantined", "killed", "logged"]] = None
    description: Optional[str] = Field(default=None, max_length=2048)

    @field_validator("ts", mode="before")
    @classmethod
    def _parse_datetime(cls, value):
        return _parse_dt(value)
